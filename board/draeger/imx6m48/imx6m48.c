static int setboardrev (struct cmd_tbl *cmdtp, int flag, int argc, char * const argv[])
{
    int ret;
    int busNum = CONFIG_SYS_EEPROM_I2C_BUS_NUM_M48;
    int boardRevOffset = CFG_SYS_I2C_BOARD_REV_OFFSET_M48;
    int addrLen = CONFIG_SYS_EEPROM_MEMADDR_LEN_M48;
    uint16_t ver;
    struct udevice *dev;
    unsigned long major;
    unsigned long minor;

    if (argc != 3) {
        return CMD_RET_USAGE;
    }

    major = simple_strtoul(argv[1], NULL, 10);
    minor = simple_strtoul(argv[2], NULL, 10);

    if (major > 0xff || minor > 0xff) {
        printf ("Major and Minor numbers must be lower than 256\n");
        return 1;
    }

    ver = (uint16_t) (minor << 8) + (uint16_t) major;

    ret = i2c_get_chip_for_busnum(busNum, CONFIG_SYS_I2C_EEPROM_ADDR,
                                  addrLen, &dev);
    if (!ret)
        ret = i2c_set_chip_offset_len(dev, addrLen);                                  

    if (!ret)
        ret = dm_i2c_write(dev, boardRevOffset, (uint8_t*) &ver, sizeof(ver));

    if (ret) {
        printf("\nEEPROM @ 0x%02x write FAILED!!!\n", boardRevOffset);
        return ret;
    }

    return 0;
}

