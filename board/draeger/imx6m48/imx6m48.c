static void rotate_logo_180(unsigned char *buf)
{
	unsigned char tmp;
	unsigned char *from;
	unsigned char *to;

	for (from = &buf[0], to = &buf[BMP_LOGO_HEIGHT * BMP_LOGO_WIDTH - 1];
			to > from; from ++, to --) {
		tmp = *from;
		*from = *to;
		*to = tmp;
	}
}


