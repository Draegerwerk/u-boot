static int do_boardrev (struct cmd_tbl *cmdtp, int flag, int argc, char * const argv[])
{
    int ret;
    int busNum = CONFIG_SYS_EEPROM_I2C_BUS_NUM_M48;
    int boardRevOffset = CFG_SYS_I2C_BOARD_REV_OFFSET_M48;
    int addrLen = CONFIG_SYS_EEPROM_MEMADDR_LEN_M48;
    uint16_t ver;
    struct udevice *dev;

    ret = i2c_get_chip_for_busnum(busNum, CONFIG_SYS_I2C_EEPROM_ADDR,
                                  1, &dev);
    if (!ret)
        ret = i2c_set_chip_offset_len(dev, addrLen);

    /* Read board revision from EEPROM */
    if (!ret)
        ret = dm_i2c_read(dev, boardRevOffset, (uchar *) &ver, sizeof(ver));

    if (ret) {

        printf("\nEEPROM @ 0x%02x read @ 0x%02x FAILED!!!\n", busNum, boardRevOffset);
        return ret;
    }

    printf ("Board revision %d.%d\n", *((char *)(&ver)), *((char *)(&ver) + 1));

    return 0;
}

